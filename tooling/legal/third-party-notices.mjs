// Generates THIRD_PARTY_NOTICES.md from the pnpm lockfile (production
// dependencies of every workspace package) plus tooling/legal/third-party-data.json
// for the Python science service and Docker images. Run: pnpm legal:notices
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(
  readFileSync("tooling/legal/third-party-data.json", "utf8"),
);
const raw = JSON.parse(
  execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }),
);

const allowed = new Set(data.openSourceAllowList);
const tokens = (expr) =>
  expr
    .replace(/[()]/g, " ")
    .split(/\s+(?:AND|OR|WITH)\s+|\s+/)
    .filter(Boolean);
const outsideAllowList = (expr) =>
  tokens(expr).filter((t) => !allowed.has(t) && !/^[a-z]/.test(t));

const packages = [];
for (const [license, list] of Object.entries(raw))
  for (const p of list)
    for (const version of p.versions)
      packages.push({
        name: p.name,
        version,
        license,
        homepage: p.homepage ?? "",
      });
packages.sort((a, b) =>
  a.name === b.name
    ? a.version.localeCompare(b.version)
    : a.name.localeCompare(b.name),
);

const counts = {};
for (const p of packages) counts[p.license] = (counts[p.license] ?? 0) + 1;
const flagged = packages.filter((p) => outsideAllowList(p.license).length > 0);

const out = [];
out.push("# Third-party notices");
out.push("");
out.push(
  `Generated by \`pnpm legal:notices\` (tooling/legal/third-party-notices.mjs). Python and Docker data last checked ${data.checkedOn}.`,
);
out.push("");
out.push(
  "Rotavise's own code is licensed under the Apache License 2.0 (see LICENSE and NOTICE). It builds on the open-source software below. Each package keeps its own licence; the licence text ships inside the package. Data sets and documents used by the tool are listed in docs/REFERENCES.md.",
);
out.push("");
out.push("## Licence summary (npm production dependencies)");
out.push("");
out.push("| Licence | Packages |");
out.push("| ------- | -------- |");
for (const [l, n] of Object.entries(counts).sort((a, b) => b[1] - a[1]))
  out.push(`| ${l} | ${n} |`);
out.push("");
out.push(
  flagged.length === 0
    ? "Every npm production dependency is under an OSI-approved licence from the allow list. No copyleft (GPL/AGPL/LGPL) or non-OSI licence was found."
    : `Outside the allow list: ${flagged.map((p) => `${p.name}@${p.version} (${p.license})`).join(", ")}. Review before release.`,
);
out.push("");
out.push(`## npm production dependencies (${packages.length})`);
out.push("");
out.push("| Package | Version | Licence |");
out.push("| ------- | ------- | ------- |");
for (const p of packages)
  out.push(`| ${p.name} | ${p.version} | ${p.license} |`);
out.push("");
out.push("## Python science service");
out.push("");
out.push(data.python.note);
out.push("");
out.push("| Package | Version | Licence |");
out.push("| ------- | ------- | ------- |");
for (const p of data.python.packages)
  out.push(`| ${p.name} | ${p.version} | ${p.license} |`);
out.push("");
out.push(
  "`tqdm` is partly under MPL-2.0, a file-level weak copyleft licence. It is used unmodified as a dependency, so the MPL-2.0 obligations apply only to tqdm's own files.",
);
out.push("");
out.push("## Docker base images");
out.push("");
out.push(data.docker.note);
out.push("");
out.push("| Image | Use | Licence |");
out.push("| ----- | --- | ------- |");
for (const i of data.docker.images)
  out.push(`| ${i.image} | ${i.use} | ${i.license} |`);
out.push("");

out.push("## Field-boundary reference data (optional)");
out.push("");
out.push(
  "Fields of The World (Robinson et al., 2026), Global agricultural field boundary map, Morocco 2025. Source: https://source.coop/ftw/global-data. Data licensed under [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/). Rotavise filters geometries, drops holes where total area change remains within 2%, simplifies boundaries at up to 5 metres and rescales known source confidence from 0–100 to 0–1. These are suggested remote-sensing outlines, not legal parcels; accuracy on Moroccan fields is unmeasured. Provenance and modifications are returned with the API data. See docs/evidence/field-boundaries/2026-11-10/field-boundaries-report.md. Dataset licence is separate from the application licence.",
);
out.push("");
out.push(
  "Research-only OSM extracts and overlays contain © OpenStreetMap contributors data under [ODbL 1.0](https://www.openstreetmap.org/copyright); no OSM data is imported into the runtime boundary service. Sentinel-2 research images: Contains modified Copernicus Sentinel data (2025). Moroccan survey geometry samples: Ouassanouan et al., [Figshare v2](https://doi.org/10.6084/m9.figshare.28486022.v2), CC BY 4.0, geometry-only excerpts; not imported into the runtime service. WorldCover and WorldCereal research map images retain their respective ESA/Copernicus product attribution; Digital Earth Africa cropland extent is CC BY 4.0. Exact source notices and hashes accompany the saved research evidence.",
);
out.push("");
writeFileSync("THIRD_PARTY_NOTICES.md", out.join("\n"));
console.log(
  `Wrote THIRD_PARTY_NOTICES.md: ${packages.length} npm packages, ${data.python.packages.length} Python packages, ${data.docker.images.length} images; ${flagged.length} outside the allow list.`,
);
